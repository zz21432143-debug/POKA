export function toolIntro(path: string) {
  return TOOL_INTROS.find((row) => row.path === path) ?? TOOL_INTROS[0];
}

export function toolMetadata(path: string): Metadata {
  const intro = toolIntro(path);
  return {
    title: intro.title,
    description: intro.description,
    alternates: { canonical: intro.path },
    openGraph: { title: intro.title, description: intro.description, url: intro.path },
  };
}
