export type PlanItem = {
  id: string;
  day: string;
  time: string;
  kind: "초보" | "핸드분석" | "정보";
  boardType: BoardType;
  boardLabel: string;
  title: string;
  /** 예전에 이 제목으로 올렸던 글(관리 화면에서 '새 내용으로 고치기'로 이어 줌) */
  oldTitles?: string[];
  /** 본문의 {{투표:계획id}} 자리를 그 핸드리뷰 글의 실제 투표 결과로 채움 */
  pollSummary?: { plan: string; choices: [PollChoiceId, string][] }[];
  content: string;
  hand?: HandReviewData;
  /** 대회 캘린더로 본문을 채우는 글 */
  schedule?: "week" | "weekend";
  /** 사진을 붙이는 글(현장 스케치) */
  photos?: boolean;
  /** 직접 핸드를 그려야 하는 글(실제 대회 핸드) */
  manualHand?: boolean;
};

