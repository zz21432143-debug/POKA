/** 상황에 맞는 대사 하나(seed가 같으면 같은 줄 · 화면이 다시 그려져도 안 바뀜) */
export function pickLine(species: YokaiSpecies, kind: LineKind, seed: number) {
  const list = YOKAI_LINES[species][kind];
  return list[Math.abs(Math.trunc(seed)) % list.length];
}
