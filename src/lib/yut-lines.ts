/** 잡은 요괴 말투로 도발 한 줄(같은 판 · 같은 순간이면 모두에게 같은 멘트) */
export function yutTaunt(species: YokaiSpecies | null | undefined, seed: number) {
  const own = (species && BY_SPECIES[species]) || [];
  // 내 요괴 멘트가 공용보다 자주 나오게
  const pool = [...own, ...own, ...own, ...COMMON];
  return pool[Math.abs(Math.floor(seed / 7)) % pool.length];
}
